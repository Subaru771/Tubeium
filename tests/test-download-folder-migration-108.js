'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {isLegacyName,migrateLegacyDownloadFolder,remapDownloadJobPaths}=require('../src/download-folder-migration');
assert(isLegacyName('uYouPlus'));
assert(isLegacyName('YouPlus PC'));
assert(!isLegacyName('Tubeium'));
assert(!isLegacyName('Movies'));
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'tubeium-108-'));
try{
 const old=path.join(dir,'uYouPlus');
 fs.mkdirSync(old);
 fs.writeFileSync(path.join(old,'keep.mp4'),'keep me');
 const result=migrateLegacyDownloadFolder({fs,base:dir,subfolder:'uYouPlus'});
 assert.equal(result.nextSubfolder,'Tubeium');
 assert.equal(result.moved,true);
 assert.equal(fs.existsSync(old),false);
 assert.equal(fs.readFileSync(path.join(dir,'Tubeium','keep.mp4'),'utf8'),'keep me','Existing downloads are preserved');
 const jobs=[{id:'a',files:[path.join(old,'keep.mp4'),path.join(dir,'elsewhere.mp4')]}];
 const migrated=remapDownloadJobPaths(jobs,old,path.join(dir,'Tubeium'));
 assert.equal(migrated[0].files[0],path.join(dir,'Tubeium','keep.mp4'));
 assert.equal(migrated[0].files[1],path.join(dir,'elsewhere.mp4'));
 assert.equal(jobs[0].files[0],path.join(old,'keep.mp4'),'Migration must not mutate stored job objects in place');
 const other=path.join(dir,'Unrelated');
 fs.mkdirSync(other);
 fs.mkdirSync(old);fs.writeFileSync(path.join(old,'old.mp4'),'old');
 const blocked=migrateLegacyDownloadFolder({fs,base:dir,subfolder:'uYouPlus'});
 assert.equal(blocked.blocked,true,'If Tubeium folder already exists, do not overwrite old downloads');
 assert.equal(blocked.moved,false);
 assert.equal(fs.readFileSync(path.join(old,'old.mp4'),'utf8'),'old');
 const custom=migrateLegacyDownloadFolder({fs,base:dir,subfolder:'Unrelated'});
 assert.equal(custom.nextSubfolder,'Unrelated');
 assert.equal(custom.source,null,'Custom paths may never be auto-renamed');
 assert.equal(custom.moved,false);
 assert.equal(fs.existsSync(old),true);
}finally{fs.rmSync(dir,{recursive:true,force:true});}
const main=fs.readFileSync(path.join(__dirname,'../src/main.js'),'utf8');
assert.match(main,/migrateLegacyDownloadFolder\(\{/);
assert.match(main,/remapDownloadJobPaths\(jobs,legacyDownloads\.source,legacyDownloads\.destination\)/);
assert.match(main,/settings=normalize\(\{downloadSubfolder:legacyDownloads\.nextSubfolder\},settings\)/);
console.log('PASS: safe legacy uYouPlus folder migration, existing files, custom paths and queue links preserved');
