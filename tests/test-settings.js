'use strict';
const assert=require('node:assert/strict');
const { DEFAULTS, normalize, metadata, publicGroups }=require('../src/settings-schema');
const groups=publicGroups();
assert.equal(groups.length,15);
assert.ok(Object.keys(DEFAULTS).length>=160,'Expected a comprehensive collection of options');
assert.equal(new Set(Object.keys(metadata)).size,Object.keys(DEFAULTS).length);
assert.equal(normalize({blockAds:false}).blockAds,false);
assert.equal(normalize({blockAds:'no'}).blockAds,true);
assert.equal(normalize({speedStep:0.5}).speedStep,'0.5','v1 numeric setting migrates');
assert.equal(normalize({pageZoom:999}).pageZoom,100,'Out-of-range values ignored');
assert.equal(DEFAULTS.dashboardFontSize,125);
assert.equal(DEFAULTS.youtubeFontSize,110);
assert.equal(normalize({dashboardFontSize:145}).dashboardFontSize,145);
assert.equal(normalize({dashboardFontSize:999}).dashboardFontSize,125,'Invalid font scaling ignored');
assert.equal(normalize({youtubeFontSize:160}).youtubeFontSize,160);
assert.equal(normalize({youtubeFontSize:85}).youtubeFontSize,110,'Invalid YouTube font scaling ignored');
assert.equal(normalize({accentColor:'red'}).accentColor,DEFAULTS.accentColor);
assert.equal(normalize({accentColor:'#FFaABb'}).accentColor,'#ffaabb');
assert.deepEqual(normalize({sbCategories:['sponsor','sponsor','intro','unknown']}).sbCategories,['sponsor','intro']);
assert.deepEqual(normalize({sbCategories:['unknown','filler']}).sbCategories,['filler']);
assert.equal(normalize({downloadSubfolder:'../../Users'}).downloadSubfolder,'Tubeium');
assert.equal(normalize({downloadSubfolder:'safe'}).downloadSubfolder,'safe');
assert.equal(normalize({downloadSubfolder:'A\\B'}).downloadSubfolder,'Tubeium');
assert.equal(normalize({speedUpKey:'Shift+ArrowRight'}).speedUpKey,'Shift+ArrowRight');
assert.equal(normalize({speedUpKey:'onload=alert(1)'}).speedUpKey,']');
assert.equal(normalize({nonexistent:'x'}).nonexistent,undefined);
assert.equal(normalize({customCSS:'a{display:none}'}).customCSS,'a{display:none}');
const original=normalize({hideShorts:false});
const changed=normalize({hideComments:true},original);
assert.equal(changed.hideShorts,false);assert.equal(changed.hideComments,true);
assert.equal(original.hideComments,false,'Merge must not modify original');
assert.equal(normalize({downloadSubLanguage:'-o /tmp'}).downloadSubLanguage,'en,ar','Reject unsafe subtitle language patterns');
assert.equal(normalize({autoFullscreen:true}).autoFullscreen,true);
assert.equal(normalize({startFullscreen:'true'}).startFullscreen,false);
assert.deepEqual(normalize({sbMutedCategories:['sponsor','outro','unknown']}).sbMutedCategories,['sponsor','outro']);
assert.equal(normalize({wheelVolumeStep:999}).wheelVolumeStep,5);
console.log('PASS:',Object.keys(DEFAULTS).length,'validated settings in',groups.length,'categories.');
