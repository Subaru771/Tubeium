'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'src/tab-strip.js'),'utf8');
const main=fs.readFileSync(path.join(root,'src/main.js'),'utf8');
const pre=fs.readFileSync(path.join(root,'src/tab-strip-preload.js'),'utf8');
const html=fs.readFileSync(path.join(root,'src/tab-strip.html'),'utf8');
const css=fs.readFileSync(path.join(root,'src/tab-strip.css'),'utf8');
const classes=()=>{const s=new Set();return {has:c=>s.has(c),toggle:(c,on)=>{if(on===undefined)on=!s.has(c);if(on)s.add(c);else s.delete(c);},add:c=>s.add(c)};};
const elements=Object.fromEntries(['yt','help','hide-tabs','show-tabs','open-settings'].map(id=>[id,{classList:classes(),handlers:{},addEventListener(type,fn){this.handlers[type]=fn;}}]));
let listener=null;
const actions=[];
const window={tubeiumTabs:{select:tab=>actions.push('select:'+tab),hide:()=>actions.push('hide'),show:()=>actions.push('show'),openSettings:()=>actions.push('settings'),onState:cb=>{listener=cb;}}};
const document={documentElement:{classList:classes()},getElementById:id=>elements[id]};
vm.runInNewContext(source,{window,document});
assert.equal(typeof listener,'function');
listener({tab:'youtube',showHelpTabs:true});
assert(!document.documentElement.classList.has('collapsed'));
assert(elements.yt.classList.has('active'));
elements['hide-tabs'].handlers.click();
assert.equal(actions.pop(),'hide');
listener({tab:'youtube',showHelpTabs:false});
assert(document.documentElement.classList.has('collapsed'),'collapsed tab strip must expose restore button');
elements['show-tabs'].handlers.click();
assert.equal(actions.pop(),'show','restore affordance must actually call the native restore action');
elements['open-settings'].handlers.click();
assert.equal(actions.pop(),'settings','Settings entry point must call the native Settings action');
listener({tab:'welcome',showHelpTabs:true});
assert(!document.documentElement.classList.has('collapsed'));
assert(elements.help.classList.has('active'));
assert.match(html,/id="show-tabs"/);
assert.match(css,/html\.collapsed #show-tabs/);
assert.match(main,/const COLLAPSED_TAB_WIDTH = 244/);
assert.match(main,/tabBarView\.setVisible\(!tabBarFullscreen\)/,'collapsed handle remains visible outside fullscreen');
assert.match(main,/tabBarView\.webContents\.send\('tubeium-tab-state', \{tab: activeTubeiumTab, showHelpTabs: helpTabsVisible\}\)/);
assert.match(pre,/ipcRenderer\.send\('tubeium-tab-show'\)/);
assert.match(main,/ipcMain\.on\('tubeium-tab-show'/);
console.log('PASS: collapsed tabs display a discoverable Show tabs button that restores full tabs');
