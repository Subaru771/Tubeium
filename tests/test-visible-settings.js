'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const src = file => fs.readFileSync(path.join(__dirname, '..', 'src', file), 'utf8');
const preload=src('preload.js'), main=src('main.js');
const tabs=src('tab-strip.html'), tabScript=src('tab-strip.js');
const bridge=src('tab-strip-preload.js'), css=src('tab-strip.css');
assert.match(preload,/label\.textContent='Settings'/,'Floating settings control needs a visible text label');
assert.match(preload,/b\.setAttribute\('aria-label','Open Tubeium settings'\)/);
assert.match(preload,/#uyp-prefs-btn\{[\s\S]*?bottom:68px/,'Settings must sit above the 42px tab strip');
assert.match(preload,/html\.uyp-hide-settings #uyp-prefs-btn\{display:none!important;\}/,'Existing setting must still hide floating control');
assert.match(tabs,/id="open-settings"[^>]*aria-label="Open Tubeium settings"/);
assert.match(tabScript,/getElementById\('open-settings'\)\.addEventListener\('click'/);
assert.match(bridge,/openSettings:\(\)=>ipcRenderer\.send\('tubeium-tab-open-settings'\)/);
assert.match(main,/ipcMain\.on\('tubeium-tab-open-settings',[\s\S]*?event\.sender!==tabBarView\.webContents\) return;[\s\S]*?openSettings\(\)/);
assert.match(css,/\.settings-shortcut\{/);
assert.match(tabs,/id="show-tabs"/,'Collapsed restore handle must remain');
assert.match(tabs,/id="hide-tabs"/,'Collapse control must remain');
console.log('PASS: Settings floating shortcut and trusted native navigation entry point');
