'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {normalizeFavorites,MAX_FAVORITES}=require('../src/settings-favorites');
const {DEFAULTS}=require('../src/settings-schema');
const keys=Object.keys(DEFAULTS);
assert.equal(MAX_FAVORITES,24);
assert.deepEqual(normalizeFavorites(['blockAds','preferredQuality','blockAds','not-real',null],keys),['blockAds','preferredQuality']);
assert.deepEqual(normalizeFavorites('blockAds',keys),[]);
assert.deepEqual(normalizeFavorites(null,keys),[]);
assert.deepEqual(normalizeFavorites(['__proto__','constructor',{}],keys),[]);
const many=[...keys.slice(0,30)];
assert.equal(normalizeFavorites(many,keys).length,24);
assert.equal(normalizeFavorites(many,keys).at(-1),many[23]);
const main=fs.readFileSync(path.join(__dirname,'../src/main.js'),'utf8');
const renderer=fs.readFileSync(path.join(__dirname,'../src/settings-renderer.js'),'utf8');
const preload=fs.readFileSync(path.join(__dirname,'../src/settings-preload.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../src/settings.html'),'utf8');
const pkg=require('../package.json');
assert.match(main,/const getFavoriteSettings = \(\) => normalizeFavorites\(readJson\(favoriteSettingsFile\(\), \[\]\), Object\.keys\(DEFAULTS\)\)/);
assert.match(main,/'prefs-set-favorites': \(_e, keys\) =>/);
assert.match(main,/normalizeFavorites\(keys, Object\.keys\(DEFAULTS\)\)/);
assert.match(main,/favorites: getFavoriteSettings\(\)/);
assert.match(preload,/setFavorites: keys => call\('prefs-set-favorites', keys\)/);
assert.match(renderer,/favoriteSettings\(\)/);
assert.match(renderer,/star\.setAttribute\('aria-pressed'/);
assert.match(renderer,/star\.onclick=\(\)=>toggleFavorite\(m\.key\)/);
assert.match(renderer,/if\(current==='favorites'\)return/,'Favorites cannot be reset as a synthetic settings category');
assert.match(html,/id="open-favorites"/);
assert(pkg.build.files.includes('src/settings-favorites.js'));
assert.equal(Object.keys(DEFAULTS).length,201,'Favorites do not change the setting schema or defaults');
console.log('PASS: persisted, validated Settings favorites, pin/unpin UI, existing 201 settings unchanged');
