'use strict';
const assert=require('node:assert/strict');
const {isGuideButtonClick,handleGuideButtonClick}=require('../src/guide-toggle');
const set=new Set(['uyp-hide-sidebar']);
const root={classList:{contains:cls=>set.has(cls),toggle:cls=>{if(set.has(cls))set.delete(cls);else set.add(cls);},remove:cls=>set.delete(cls)}};
const guide={matches:selector=>selector.includes('ytd-masthead #guide-button')};
const normal={matches:()=>false};
const click={target:normal,composedPath:()=>[normal,guide]};
assert(isGuideButtonClick(click),'must recognize YouTube guide button through a composed event path');
assert(!isGuideButtonClick({target:normal,composedPath:()=>[normal]}));
assert(handleGuideButtonClick(click,root));
assert(set.has('uyp-guide-open'),'first click permits the native drawer to show');
assert(handleGuideButtonClick(click,root));
assert(!set.has('uyp-guide-open'),'second click restores the hide-sidebar preference');
assert(!handleGuideButtonClick({target:normal,composedPath:()=>[normal]},root));
assert(!set.has('uyp-guide-open'),'unrelated clicks do not open the guide');
set.delete('uyp-hide-sidebar');
assert(!handleGuideButtonClick(click,root),'normal YouTube guide click is untouched if hide-sidebar is disabled');
console.log('PASS: YouTube guide button overrides hidden sidebar without intercepting native click');
