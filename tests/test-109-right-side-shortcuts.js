'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {DEFAULTS,metadata,publicGroups,normalize}=require('../src/settings-schema');
const read=x=>fs.readFileSync(path.join(__dirname,'../src',x),'utf8');
const preload=read('preload.js'),main=read('main.js'),html=read('tab-strip.html'),tabScript=read('tab-strip.js');
assert.equal(Object.keys(DEFAULTS).length,201,'Preserve all preferences');
assert.equal(publicGroups().length,15);
assert.equal(DEFAULTS.showDownloadButton,true);
assert.equal(DEFAULTS.showSigninHelpButton,true);
assert.equal(metadata.showDownloadButton.group,'downloads');
assert.equal(metadata.showSigninHelpButton.group,'downloads');
assert.equal(normalize({showDownloadButton:false}).showDownloadButton,false);
assert.equal(normalize({showSigninHelpButton:false}).showSigninHelpButton,false);
assert.equal(normalize({downloadPosition:'left'}).downloadPosition,undefined);
assert(!/\bid\s*=\s*['"]uyp-dl-left['"]/.test(preload));
assert.doesNotMatch(preload,/#uyp-prefs-btn/);
assert.doesNotMatch(preload,/tubeium-signin-help/);
assert.match(preload,/function positionDownloadDock\(\)/);
assert.match(preload,/ytd-watch-metadata #actions/);
assert.match(preload,/dock\.classList\.add\('tubeium-dock-fallback','tubeium-dock-active'\)/);
assert.match(preload,/setInterval\(updateDock,750\)/);
assert.match(preload,/dock\.append\(box\);document\.body\.appendChild\(dock\)/);
assert.match(preload,/if\(btn\)btn\.hidden=state\.showDownloadButton===false/);
assert.match(preload,/rightActions\.hidden=state\.showDownloadButton===false/);
assert.match(html,/id="menu-help"/);
assert.match(html,/id="menu-settings"/);
assert.match(tabScript,/showSigninHelpButton!==false/);
assert.match(main,/ipcMain\.on\('tubeium-tab-menu-toggle'/);
assert.match(main,/ipcMain\.on\('tubeium-tab-open-settings'/);
const mainClick=preload.match(/main\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\);/);
assert(mainClick);assert.match(mainClick[1],/void start\('video'\)/);
assert.doesNotMatch(mainClick[1],/open-download-manager|classList\.toggle\('open'\)|tubeium-open-signin-help/);
const more=preload.match(/options\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\);/);
assert(more);assert.match(more[1],/classList\.toggle\('open'\)/);
const manager=preload.match(/managerButton\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\)/);
assert(manager);assert.match(manager[1],/ipcRenderer\.send\('open-download-manager'\)/);
console.log('PASS: no floating Settings, no redundant sign-in prompt, Download in video actions and one native menu');
