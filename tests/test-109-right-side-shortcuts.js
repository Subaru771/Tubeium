'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {DEFAULTS,metadata,publicGroups,normalize}=require('../src/settings-schema');
const root=path.join(__dirname,'..');
const preload=fs.readFileSync(path.join(root,'src/preload.js'),'utf8');
const main=fs.readFileSync(path.join(root,'src/main.js'),'utf8');
const schema=fs.readFileSync(path.join(root,'src/settings-schema.js'),'utf8');
const html=fs.readFileSync(path.join(root,'src/settings.html'),'utf8');
assert.equal(Object.keys(DEFAULTS).length,201,'Keep 201 original settings total');
assert.equal(publicGroups().length,15);
assert.equal(DEFAULTS.showDownloadButton,true);
assert.equal(DEFAULTS.showSigninHelpButton,true);
assert.equal(metadata.showDownloadButton.group,'downloads');
assert.equal(metadata.showSigninHelpButton.group,'downloads');
assert.equal(normalize({showSigninHelpButton:false}).showSigninHelpButton,false);
assert.equal(normalize({showDownloadButton:false,showSigninHelpButton:true}).showDownloadButton,false);
assert.equal(normalize({showDownloadButton:true,showSigninHelpButton:false}).showSigninHelpButton,false);
assert.equal(normalize({downloadPosition:'left'}).downloadPosition,undefined,
  'Saved bottom-left position must no longer produce a left Download button');
assert(!schema.includes('uyp-dl-left'));
assert(!preload.includes('uyp-dl-left'));
assert(!preload.includes('state.downloadPosition'));
assert.match(preload,/#tubeium-right-actions\{position:fixed;right:18px;bottom:74px/);
assert.match(preload,/#tubeium-signin-help\{display:inline-flex/);
assert.match(preload,/#uyp-dl\{display:none;position:relative/);
assert.match(preload,/#uyp-dl \.uyp-menu\{position:absolute;bottom:calc\(100% \+ 8px\);right:0/);
assert.match(preload, /signinHelp\.textContent='Have a problem signing in\?'/);
assert.match(preload, /signinHelp\.addEventListener\('click',event=>\{/);
assert.match(preload, /ipcRenderer\.send\('tubeium-open-signin-help'\)/);
assert.match(main,/ipcMain\.on\('tubeium-open-signin-help',e=>\{/);
assert.match(main,/if\(!ytOnly\(e\)\)return;[\s\S]{0,100}showWindow\(\);[\s\S]{0,50}openWelcomeTab\(\);/);
assert.match(preload,/if\(btn\)btn\.hidden=state\.showDownloadButton===false/);
assert.match(preload,/if\(signinHelp\)signinHelp\.hidden=state\.showSigninHelpButton===false/);
assert.match(preload,/rightActions\.hidden=state\.showDownloadButton===false&&state\.showSigninHelpButton===false/);
assert.match(preload,/dock\.append\(signinHelp,box\);document\.body\.appendChild\(dock\)/);
const mainClick=preload.match(/main\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\);/);
assert(mainClick);
assert.match(mainClick[1],/void start\('video'\)/);
assert.doesNotMatch(mainClick[1],/open-download-manager|classList\.toggle\('open'\)|tubeium-open-signin-help/);
const optionsClick=preload.match(/options\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\);/);
assert(optionsClick);
assert.match(optionsClick[1],/box\.classList\.toggle\('open'\)/);
assert.doesNotMatch(optionsClick[1],/start\('video'\)|open-download-manager/);
const managerClick=preload.match(/managerButton\.addEventListener\('click',event=>\{([\s\S]*?)\n  \}\)/);
assert(managerClick);
assert.match(managerClick[1],/ipcRenderer\.send\('open-download-manager'\)/);
assert.match(html,/1\.09/);
console.log('PASS: bottom-right only controls, separate show/hide preferences, isolated Download/More/Manager/Sign-in actions');
